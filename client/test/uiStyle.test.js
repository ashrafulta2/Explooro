/**
 * uiStyle.test.js — invariants of the component style layer (services/uiStyle.ts).
 *
 *   1. The client and the server agree on which styles exist. The server refuses an unknown
 *      `ui_style` on save; the client quietly reads one as 'standard'. If the lists drift, an admin
 *      can preview a style the API will not save, or save one no browser draws.
 *   2. Every preset that names a style names a real one.
 *   3. ui-macos.css is inert until the attribute is set, names no colour of its own (the master
 *      palette owns colour), carries no gradient or glass, and stays out of the entry bundle.
 */

import test, { describe } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { UI_STYLES, normaliseUiStyle, DEFAULT_UI_STYLE } from '../src/services/uiStyle.ts';
import { MASTER_PRESETS } from '../src/config/master-themes.ts';

const CLIENT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (...p) => readFileSync(join(CLIENT, ...p), 'utf8');

const macosCss = read('src', 'styles', 'ui-macos.css');
/** The CSS with comments removed, so the header's prose cannot trip the checks. */
const css = macosCss.replace(/\/\*[\s\S]*?\*\//g, '');

test('server UI_STYLES equals the client list', () => {
  // Read as text: importing theme.service.ts would pull the repository and database layer.
  const src = read('..', 'server', 'src', 'services', 'theme.service.ts');
  const m = src.match(/export const UI_STYLES = (\[[^\]]*\])/);
  assert.ok(m, 'theme.service.ts no longer exports UI_STYLES as an array literal');
  const serverList = JSON.parse(m[1].replace(/'/g, '"'));
  assert.deepEqual(serverList, [...UI_STYLES]);
});

test('unknown or missing styles read as the default', () => {
  assert.equal(DEFAULT_UI_STYLE, 'standard');
  assert.equal(normaliseUiStyle(undefined), 'standard');
  assert.equal(normaliseUiStyle('aqua'), 'standard');
  assert.equal(normaliseUiStyle('macos'), 'macos');
});

test('every preset style is a known style, and the macOS preset uses the macos style', () => {
  for (const [key, preset] of Object.entries(MASTER_PRESETS)) {
    if (preset.uiStyle !== undefined) assert.ok(UI_STYLES.includes(preset.uiStyle), `${key}: ${preset.uiStyle}`);
  }
  assert.equal(MASTER_PRESETS.macos_native?.uiStyle, 'macos');
});

test('every rule in ui-macos.css is scoped to the macos attribute', () => {
  // Split on rule bodies; whatever precedes a `{` that is not an at-rule is a selector list.
  const selectors = [];
  for (const m of css.matchAll(/([^{}]+)\{/g)) {
    const head = m[1].trim();
    if (!head || head.startsWith('@')) continue;
    selectors.push(...head.split(',').map((s) => s.trim()).filter(Boolean));
  }
  assert.ok(selectors.length > 40, 'parsed suspiciously few selectors');
  const loose = selectors.filter((s) => !s.startsWith(":root[data-ui-style='macos']"));
  assert.deepEqual(loose, [], 'unscoped selectors would restyle the standard look');
});

test('ui-macos.css names no colour of its own, no gradient and no glass', () => {
  assert.doesNotMatch(css, /#[0-9a-fA-F]{3,8}\b/, 'raw hex — use a token');
  assert.doesNotMatch(css, /gradient/i);
  assert.doesNotMatch(css, /backdrop-filter/i);
});

test('controls a user types in or picks from keep their 3:1 border', () => {
  // WCAG 1.4.11: input-affordance.css gives every field, select, checkbox and radio the
  // --border-interactive edge. A soft Mac hairline (a transparent border, or --border-strong at
  // ~1.5:1) would make them read as plain text again. Buttons may use the bezel; these may not.
  const control = /(\.field__control|\.form-(input|select|textarea)|\.(input|select|textarea)\b|\bselect\b|\.checkbox__box|\.radio__box)/;
  const offenders = [];
  for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const head = m[1].trim();
    if (head.startsWith('@')) continue;
    for (const sel of head.split(',').map((s) => s.trim())) {
      if (!control.test(sel)) continue;
      if (/:checked|:indeterminate|\.toggle__input|chevron|option/.test(sel)) continue;
      if (/border(-color)?:[^;]*(transparent|--border-strong)/.test(m[2])) offenders.push(sel);
    }
  }
  assert.deepEqual(offenders, []);
});

test('ui-macos.css and its generated page twins stay out of the entry bundle', () => {
  assert.doesNotMatch(read('src', 'styles', 'main.css'), /ui-macos/);
  const service = read('src', 'services', 'uiStyle.ts');
  assert.match(service, /import\('\.\.\/styles\/ui-macos\.css'\)/);
  assert.match(service, /import\('\.\.\/styles\/ui-macos-pages\.css'\)/);
});

describe('ui-macos-pages.css (generated by scripts/macos-pages.mjs)', () => {
  const pages = read('src', 'styles', 'ui-macos-pages.css');
  const body = pages.replace(/\/\*[\s\S]*?\*\//g, '');

  test('each rewrite does what its comment says, and leaves the rest alone', async () => {
    const { twinSheet } = await import('../../scripts/macos-pages.mjs');
    const one = (css) => twinSheet(css).join('\n');
    // uppercase → none, and its tracking only when the rule set some
    assert.match(one('.a { text-transform: uppercase; letter-spacing: .1em; }'), /text-transform: none;\s+letter-spacing: normal/);
    // black weights → bold; a push button's bold → medium; a chip keeps its weight
    assert.match(one('.a { font-weight: 900; }'), /font-weight: 700/);
    assert.match(one('.x-btn { font-weight: 700; }'), /font-weight: var\(--weight-medium\)/);
    assert.equal(one('.x-chip { font-weight: 700; }'), '');
    // capsule push button → 6px; a round icon button (equal sides) and a chip keep their shape
    assert.match(one('.save-btn { border-radius: 9999px; }'), /border-radius: var\(--radius-sm\)/);
    assert.equal(one('.save-btn { border-radius: 9999px; width: 32px; height: 32px; }'), '');
    assert.equal(one('.close-btn { border-radius: 9999px; }'), '');
    // hover lift capped at 1px; a 1px lift is already Mac
    assert.match(one('.c:hover { transform: translateY(-4px); }'), /translateY\(-1px\)/);
    assert.equal(one('.c:hover { transform: translateY(-1px); }'), '');
    // hand-typed drop shadow → elevation; token shadows and selection rings are left alone
    assert.match(one('.c { box-shadow: 0 8px 24px rgba(0,0,0,.1); }'), /var\(--elevation-3\)/);
    assert.equal(one('.c { box-shadow: var(--elevation-2); }'), '');
    assert.equal(one('.c--on { box-shadow: 0 0 0 2px var(--brand); }'), '');
    // brand stripe → hairline, unless the stripe marks a state
    assert.match(one('.card { border-left: 4px solid var(--brand); }'), /border-left: var\(--border-width\) solid var\(--border-subtle\)/);
    assert.equal(one('.item.unread { border-inline-start: 3px solid var(--brand); }'), '');
    assert.equal(one('.alert { border-left: 4px solid var(--danger); }'), '');
    // focus ring → halo, only while forced colours are off
    assert.match(one('.c:focus-visible { outline: 2px solid var(--focus-ring); }'), /@media \(forced-colors: none\)[\s\S]*outline: none;[\s\S]*var\(--mac-focus\)/);
    // scoping keeps the original's place in the cascade, including inside @media and from :root
    assert.match(one('@media (max-width: 600px) { .a { font-weight: 800; } }'), /^@media \(max-width: 600px\) \{\n  html:where\(\[data-ui-style='macos'\]\) \.a \{/);
    assert.match(one(":root[data-theme='dark'] .a { font-weight: 800; }"), /^html:root:where\(\[data-ui-style='macos'\]\)\[data-theme='dark'\] \.a \{/);
    // !important survives, @keyframes is not touched
    assert.match(one('.a { font-weight: 900 !important; }'), /font-weight: 700 !important/);
    assert.equal(one('@keyframes k { from { box-shadow: 0 2px 4px rgba(0,0,0,.2); } }'), '');
  });

  test('is current: a page sheet changed without re-running the script', async () => {
    const { generateMacosPagesCss } = await import('../../scripts/macos-pages.mjs');
    assert.equal(pages, generateMacosPagesCss().css, 'stale — run `node scripts/macos-pages.mjs --write`');
  });

  test('every twin is scoped with exactly one extra type selector of weight', () => {
    // `html:where(...)` keeps a twin one notch above its original and below every state rule
    // that already outranked it. Any other prefix would change which rule wins.
    const selectors = [];
    for (const m of body.matchAll(/([^{}]+)\{/g)) {
      const head = m[1].trim();
      if (!head || head.startsWith('@')) continue;
      selectors.push(...head.split(/,\s*\n/).map((s) => s.trim()).filter(Boolean));
    }
    assert.ok(selectors.length > 200, `parsed only ${selectors.length} selectors`);
    const loose = selectors.filter((s) => !s.startsWith("html:where([data-ui-style='macos'])") && !s.startsWith("html:root:where([data-ui-style='macos'])"));
    assert.deepEqual(loose, []);
  });

  test('names no colour, gradient or glass, and draws focus only while forced colours are off', () => {
    assert.doesNotMatch(body, /#[0-9a-fA-F]{3,8}\b/);
    assert.doesNotMatch(body, /gradient|backdrop-filter/i);
    for (const m of body.matchAll(/var\(--mac-focus\)/g)) {
      const before = body.slice(0, m.index);
      const lastMedia = before.lastIndexOf('@media (forced-colors: none)');
      const lastClose = before.lastIndexOf('\n}\n');
      assert.ok(lastMedia > lastClose, 'a focus halo outside @media (forced-colors: none) would hide focus in high-contrast mode');
    }
  });
});
